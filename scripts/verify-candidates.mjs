// Turns scripts/candidates.mjs into a vocabulary file.
//
// A candidate survives only if English Wikipedia has an article of exactly that
// name — no redirect to something else — carrying a lead image. That is the
// whole mismatch guarantee: the picture is the article's own lead image, and
// the article is the word.
//
//   node scripts/verify-candidates.mjs

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { candidateList } from './candidates.mjs';
import { vocabulary as curated } from './vocabulary.mjs';

const UA = 'WordBloom/2.0 (student learning site; educational use)';
const OUT = path.join(process.cwd(), 'scripts', 'vocabulary.harvested.mjs');
const CACHE_FILE = path.join(process.cwd(), '.cache', 'candidates.json');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const title = (word) => word.charAt(0).toUpperCase() + word.slice(1);

/** Common uncountable nouns, so the sentence reads "This is milk." */
const MASS = new Set(`bread cheese milk honey water juice tea coffee butter sugar salt
  chocolate pasta soup popcorn corn flour cream custard gravy jam jelly icing
  ketchup mayonnaise mustard vinegar yoghurt porridge oatmeal rice barley bran
  wheat yeast cocoa marzipan nougat toffee fudge liquorice
  snow rain sand grass fire ice sunshine sunlight fog mist wind hail lightning
  thunder dew frost sleet slush smog humidity drizzle hay moss pollen soil mud lava
  paper chalk cardboard ink glue tape silk lace denim corduroy chiffon wire
  hair skin muscle furniture crockery cutlery stationery homework music`
  .split(/\s+/).filter(Boolean));

async function api(params) {
  const url = new URL('https://en.wikipedia.org/w/api.php');
  Object.entries({ format: 'json', formatversion: '2', origin: '*', ...params }).forEach(([k, v]) =>
    url.searchParams.set(k, v),
  );
  for (let attempt = 0; ; attempt += 1) {
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (res.ok) return res.json();
    if (attempt >= 6 || (res.status !== 429 && res.status < 500)) {
      throw new Error(`${res.status} ${res.statusText}`);
    }
    const wait = Number(res.headers.get('retry-after')) * 1000 || 1500 * 2 ** attempt;
    process.stdout.write(`[${res.status} ${Math.round(wait / 1000)}s]`);
    await sleep(wait);
  }
}

const chunk = (arr, size) =>
  Array.from({ length: Math.ceil(arr.length / size) }, (_, i) => arr.slice(i * size, i * size + size));

async function main() {
  const cache = await readFile(CACHE_FILE, 'utf8').then(JSON.parse).catch(() => ({}));
  const taken = new Set(curated.map((e) => e.word));
  const wanted = candidateList().filter((c) => !taken.has(c.word));

  const pending = wanted.filter((c) => cache[c.word] === undefined);
  console.log(`${wanted.length} candidates, ${pending.length} still to check`);

  for (const batch of chunk(pending, 45)) {
    const data = await api({
      action: 'query',
      prop: 'pageimages',
      piprop: 'thumbnail',
      pithumbsize: '640',
      redirects: '1',
      titles: batch.map((c) => title(c.word)).join('|'),
    });

    // A redirect means the article is really about something else under another
    // name, which is exactly where mismatches come from — so those are dropped.
    const redirected = new Set((data.query?.redirects ?? []).map((r) => r.from));
    const withImage = new Set(
      (data.query?.pages ?? []).filter((p) => p.thumbnail?.source).map((p) => p.title),
    );

    for (const candidate of batch) {
      const asked = title(candidate.word);
      cache[candidate.word] = !redirected.has(asked) && withImage.has(asked);
    }
    await mkdir(path.dirname(CACHE_FILE), { recursive: true });
    await writeFile(CACHE_FILE, JSON.stringify(cache));
    process.stdout.write('.');
    await sleep(300);
  }
  process.stdout.write('\n');

  const kept = wanted.filter((c) => cache[c.word]);
  const counts = {};
  for (const c of kept) counts[c.category] = (counts[c.category] ?? 0) + 1;

  const body = kept
    .map((c) => {
      const article = /^[aeiou]/.test(c.word) ? ", article: 'an'" : '';
      const mass = MASS.has(c.word) ? ', mass: true' : '';
      return `  { word: '${c.word}', wiki: '${title(c.word)}', category: '${c.category}'${article}${mass} },`;
    })
    .join('\n');

  await writeFile(
    OUT,
    `// GENERATED by scripts/verify-candidates.mjs — do not edit by hand.\n` +
      `//\n` +
      `// Each word here has an English Wikipedia article of exactly that name,\n` +
      `// carrying a lead image, so the photograph shows the word itself.\n` +
      `// Hand-corrected words belong in vocabulary.mjs, which always wins.\n\n` +
      `export const harvested = [\n${body}\n];\n`,
  );

  console.log(counts);
  console.log(`\nKept ${kept.length} of ${wanted.length}; total vocabulary ${curated.length + kept.length}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
